// The Juice Score methodology page: docs/LIVABILITY.md rendered as a page of
// the site itself, so "How it's calculated" never leaves the site.
//
//   static build:  dist/methodology/index.html + dist/methodology/methodology.css
//   server mode:   GET /methodology/ and /methodology/methodology.css
//                  (server/index.js; same renderer, so both modes match)
//
// renderMethodologyPage({ md, sha }) -> HTML string. Asset and app links are
// relative to the page ("../styles.css", "../"), so it works under the Pages
// sub-path and at /methodology/ on the server. CSP-clean: no inline script or
// style elements (styles come from methodology.css).
import { mdToHtml, esc } from './md.js';

/** Files under docs/ that the page may link to (by their site path). Everything else -> text. */
const SITE_LINKS = new Map([
  ['../data/cities.json', '../api/cities.json'], // the published copy of the data
]);

/** Link policy for the rendered doc: keep in-site targets, turn the rest into text. */
function linkFor(href) {
  if (SITE_LINKS.has(href)) return SITE_LINKS.get(href);
  return null;
}

