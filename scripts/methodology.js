/**
 * @param {{ md: string, sha?: string|null }} opts
 * @returns {string} a complete HTML page
 */
export function renderMethodologyPage({ md, sha = null } = {}) {
  const { html, headings } = mdToHtml(md, { link: linkFor });
  const title = (headings.find((h) => h.level === 1) || { text: 'Juice Score methodology' }).text;
  const toc = headings.filter((h) => h.level === 2)
    .map((h) => `<li><a href="#${esc(h.id)}">${esc(h.text)}</a></li>`).join('');
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)} — melon·seek</title>
  <meta name="description" content="How melon·seek's Juice Score is calculated: the formula, tax model, data sources and limitations.">
  <meta name="color-scheme" content="light dark">
  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../styles.css">
  <link rel="stylesheet" href="methodology.css">
  <script src="../theme-init.js"></script>
</head>
<body>
  <nav class="doc-top" aria-label="Site">
    <a class="doc-brand" href="../"><img src="../favicon.svg" alt="" width="22" height="22"> melon·seek</a>
    <a href="../">← Back to the jobs</a>
  </nav>
  <main class="doc-page">
    <p class="doc-note">The method behind the Juice Score shown in each job's drawer. An estimate, not financial advice.</p>
    ${toc ? `<nav class="doc-toc" aria-label="Contents"><strong>Contents</strong><ol>${toc}</ol></nav>` : ''}
    ${html}
    <footer class="doc-foot">Rendered from <code>docs/LIVABILITY.md</code>${sha ? ` at build <code>${esc(String(sha).slice(0, 12))}</code>` : ''}. Source references are shown as text; open them yourself if you want to check a figure. <a href="../">Back to melon·seek</a>.</footer>
  </main>
</body>
</html>
`;
}
